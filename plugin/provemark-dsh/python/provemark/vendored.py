from __future__ import annotations

import datetime as dt
from dataclasses import dataclass
from pathlib import Path

from . import __version__, fossa_deps
from .generated import write as write_generated
from .rules import license_data

MARKER = "<!-- generated by provemark"
DEFAULT_NAME = "VENDORED.md"
PENDING = "待补齐"
LICENSE_NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING", "COPYING.md")
MAX_LICENSE_BYTES = 200_000
PACKAGE_MANAGED = {"node_modules", "bower_components", "jspm_packages", "pods", "carthage"}


@dataclass
class VendoredEntry:
    name: str
    path: str
    license: str


def license_of(directory: Path) -> str:
    for name in LICENSE_NAMES:
        path = directory / name
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")[:MAX_LICENSE_BYTES]
        except OSError:
            continue
        return license_data.detect_from_text(text)
    return ""


def detect(root: Path, config: object | None = None) -> tuple[list[VendoredEntry], bool]:
    """Find vendored directories that carry their own LICENSE.

    ``config`` is the loaded policy; only exclusions the *user* added drop a
    directory here. The built-in defaults exclude `vendor/**` from content
    scanning on purpose, and these attribution rules exist precisely for those
    directories — so default exclusions must not silence SCP-014/015.
    """
    entries, truncated = fossa_deps.vendored_entries(root)
    excluded_by_user = getattr(config, "is_excluded_by_user", None) if config is not None else None
    kept = []
    for name, rel in entries:
        if any(part.lower() in PACKAGE_MANAGED for part in rel.split("/")):
            continue
        if callable(excluded_by_user) and excluded_by_user(rel):
            continue
        kept.append((name, rel))
    return (
        [VendoredEntry(name=name, path=rel, license=license_of(root / rel)) for name, rel in kept],
        truncated,
    )


def render(entries: list[VendoredEntry], truncated: bool = False) -> str:
    stamp = dt.datetime.now().astimezone().isoformat(timespec="seconds")
    lines = [
        f"{MARKER} {__version__} — 重新生成会覆盖本文件，手写内容请放到别的文件 -->",
        "# Vendored 代码来源",
        "",
        f"> 生成时间：{stamp}",
        f"> 共 {len(entries)} 个 vendored 目录。上游与版本/Commit 需要人工补齐（标记为「待补齐」），补齐后才能用于审计。",
        "",
        "| 目录 | 许可证 | 上游 | 版本 / Commit | 修改说明 |",
        "| --- | --- | --- | --- | --- |",
    ]
    for item in entries:
        lines.append(
            f"| {item.path} | {item.license or '未识别'} | {PENDING} | {PENDING} | 未修改 |"
        )
    lines.append("")
    if truncated:
        lines.extend(["> 注意：目录数量超过上限，仅列出前 200 个，请手工补充其余条目。", ""])
    lines.extend(
        [
            "## 说明",
            "",
            "- vendored 代码不改变其原始许可证，请保留上游 LICENSE 原文。",
            "- 修改过上游文件时，在「修改说明」里写清楚改了什么，便于升级时重新应用。",
            "- 升级 vendored 代码后重新生成：`provemark vendored --force`。",
            "",
        ]
    )
    return "\n".join(lines)


def missing_entries(text: str, entries: list[VendoredEntry]) -> list[VendoredEntry]:
    lowered = text.lower()
    return [item for item in entries if item.path.lower() not in lowered]


def pending_count(text: str) -> int:
    return text.count(f"{PENDING} |")


def write(target: Path, entries: list[VendoredEntry], truncated: bool = False, *, force: bool = False):
    return write_generated(render(entries, truncated), target, marker=MARKER, force=force)
