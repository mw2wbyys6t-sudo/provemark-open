from __future__ import annotations

import datetime as dt
from dataclasses import dataclass
from pathlib import Path

from . import __version__, ecosystems
from .cache import Cache
from .config import Config
from .scanners import deps as deps_scanner
from .scanners import files as files_scanner
from .scanners import license as license_scanner
from .scanners.base import Context

MARKER = "<!-- generated by provemark"
DEFAULT_NAME = "THIRD_PARTY_NOTICES.md"
BUILD_ONLY = {"GitHub Actions"}
UNKNOWN = "UNKNOWN"


@dataclass
class Entry:
    name: str
    version: str
    license: str
    ecosystem: str


def build_context(root: Path, config: Config, *, offline: bool = False) -> Context:
    collected, _ = files_scanner.collect_files(root, config)
    return Context(
        root=root,
        config=config,
        files=collected,
        deps=deps_scanner.collect(root, config),
        cache=Cache(),
        offline=offline,
    )


def collect(ctx: Context) -> tuple[list[Entry], int]:
    packages = [
        item
        for item in ctx.deps.packages
        if item.ecosystem not in BUILD_ONLY and item.scope != "dev"
    ]
    targets = [
        item
        for item in packages
        if item.version and ecosystems.license_lookup_supported(item.ecosystem)
    ]
    resolved = license_scanner.resolve_licenses(ctx, targets)
    entries = [
        Entry(
            name=item.name,
            version=item.version or item.declared,
            license=resolved.get(item.key, "") or UNKNOWN,
            ecosystem=item.ecosystem,
        )
        for item in packages
    ]
    entries.sort(key=lambda item: (item.ecosystem, item.name.lower()))
    unknown = sum(1 for item in entries if item.license == UNKNOWN)
    return entries, unknown


def render(entries: list[Entry], unknown: int) -> str:
    stamp = dt.datetime.now().astimezone().isoformat(timespec="seconds")
    lines = [
        f"{MARKER} {__version__} — 重新生成会覆盖本文件，手写内容请放到别的文件 -->",
        "# Third-Party Notices",
        "",
        f"> 生成时间：{stamp}",
        f"> 覆盖 {len(entries)} 个第三方组件，其中 {unknown} 个许可证未知。",
        "",
    ]
    if entries:
        lines.extend(
            [
                "| 组件 | 版本 | 许可证 | 生态 |",
                "| --- | --- | --- | --- |",
            ]
        )
        for item in entries:
            lines.append(
                f"| {item.name} | {item.version or '未固定'} | {item.license} | {item.ecosystem} |"
            )
        lines.append("")

    unknown_entries = [item for item in entries if item.license == UNKNOWN]
    if unknown_entries:
        lines.extend(["## 许可证未知", "", "以下组件未能获取许可证，分发前需人工补齐：", ""])
        for item in unknown_entries:
            lines.append(f"- `{item.name}` {item.version or ''}（{item.ecosystem}）".rstrip())
        lines.append("")

    lines.extend(
        [
            "## 说明",
            "",
            "- 本文件由 `provemark notices` 生成，结论不构成法律意见。",
            "- GitHub Actions 等仅在构建期使用的依赖未计入分发归因。",
        ]
    )
    return "\n".join(lines) + "\n"


def write(entries: list[Entry], unknown: int, target: Path, *, force: bool = False) -> tuple[Path, bool]:
    target = target.expanduser()
    redirected = False
    if target.exists():
        try:
            existing = target.read_text(encoding="utf-8", errors="replace")
        except OSError:
            existing = ""
        if MARKER not in existing and not force:
            target = target.with_name(f"{target.stem}.provemark{target.suffix}")
            redirected = True
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(entries, unknown), encoding="utf-8")
    return target, redirected
