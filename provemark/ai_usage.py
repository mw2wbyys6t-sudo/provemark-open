from __future__ import annotations

import datetime as dt
from pathlib import Path

from . import __version__
from .generated import write as write_generated

MARKER = "<!-- generated by provemark"
DEFAULT_NAME = "AI_USAGE.md"
PLACEHOLDER = "待填写"
REQUIRED_SECTIONS = ("使用的工具", "使用范围", "人工复核")
ASSISTANT_ARTIFACTS = (
    ".cursorrules",
    ".cursor",
    ".windsurfrules",
    ".clinerules",
    ".aider.conf.yml",
    ".aider.chat.history.md",
    ".continue",
    ".codeium",
    "CLAUDE.md",
    "AGENTS.md",
    "GEMINI.md",
    ".github/copilot-instructions.md",
)


def detect_artifacts(root: Path) -> list[str]:
    found = []
    for rel in ASSISTANT_ARTIFACTS:
        if (root / rel).exists():
            found.append(rel)
    return found


def render(artifacts: list[str]) -> str:
    stamp = dt.datetime.now().astimezone().isoformat(timespec="seconds")
    lines = [
        f"{MARKER} {__version__} — 重新生成会覆盖本文件，手写内容请放到别的文件 -->",
        "# AI 使用声明",
        "",
        f"> 生成时间：{stamp}",
        "> 本文件说明本项目如何使用 AI 辅助工具，是「原创性可自证」的一部分。"
        "不填写不会让代码变差，但尽调时无法自证。",
        "",
    ]
    for section, hint in (
        ("使用的工具", "工具与模型名，例：GitHub Copilot 补全 / Claude Code 重构"),
        ("使用范围", "哪些目录或模块由 AI 参与生成或修改，哪些完全手写"),
        ("人工复核", "谁复核、怎么复核：测试 / 代码审查 / 逐行检查 / 只用于样板代码"),
        ("生成内容留存", "prompt 或会话记录是否留存、存放在哪里；不适用就写「未留存」"),
    ):
        lines.extend([f"## {section}", f"<!-- {hint} -->", f"- {PLACEHOLDER}", ""])

    lines.extend(["## 检测到的 AI 工具痕迹", ""])
    if artifacts:
        for item in artifacts:
            lines.append(f"- `{item}`")
    else:
        lines.append("- 未检测到（如果确实用过 AI，请手动补充工具与范围）")
    lines.extend(
        [
            "",
            "## 第三方代码与许可证",
            "",
            "- 依赖与许可证见 `THIRD_PARTY_NOTICES.md`；vendored 代码见 `VENDORED.md`。",
            "",
        ]
    )
    return "\n".join(lines)


def missing_sections(text: str) -> list[str]:
    return [section for section in REQUIRED_SECTIONS if f"## {section}" not in text]


def unfilled_placeholders(text: str) -> int:
    return text.count(PLACEHOLDER)


def write(target: Path, artifacts: list[str], *, force: bool = False) -> tuple[Path, bool]:
    return write_generated(render(artifacts), target, marker=MARKER, force=force)
