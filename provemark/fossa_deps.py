from __future__ import annotations

import datetime as dt
import json
from dataclasses import dataclass, field
from pathlib import Path

from . import __version__, yaml_lite
from .config import Config
from .scanners import deps
from .scanners.fossa import FOSSA_DEPS_NAMES, vendor_dirs

MARKER = "# generated by provemark"
DEFAULT_LIMIT = 5000
MAX_VENDOR_ENTRIES = 200
MAX_VENDOR_DEPTH = 3
MAX_VENDOR_CHILDREN = 40
LICENSE_PREFIXES = ("license", "licence", "copying")

ECOSYSTEM_TYPES = {
    "PyPI": "pypi",
    "npm": "npm",
    "Go": "go",
    "crates.io": "cargo",
    "Maven": "maven",
    "NuGet": "nuget",
    "RubyGems": "gem",
    "Packagist": "composer",
    "Pub": "pub",
    "Hex": "hex",
    "CRAN": "cran",
    "Hackage": "hackage",
    "CPAN": "cpan",
    "SwiftURL": "swift",
}


@dataclass
class DepsPlan:
    mode: str = "missing"
    referenced: list[tuple[str, str, str]] = field(default_factory=list)
    vendored: list[tuple[str, str]] = field(default_factory=list)
    skipped: dict[str, int] = field(default_factory=dict)
    unpinned: int = 0
    total_packages: int = 0
    truncated: bool = False
    vendored_truncated: bool = False

    @property
    def empty(self) -> bool:
        return not self.referenced and not self.vendored

    def skip(self, reason: str, count: int = 1) -> None:
        self.skipped[reason] = self.skipped.get(reason, 0) + count


def _has_license(directory: Path) -> bool:
    try:
        for child in directory.iterdir():
            if child.is_file() and child.name.lower().startswith(LICENSE_PREFIXES):
                return True
    except OSError:
        return False
    return False


def vendored_entries(root: Path) -> tuple[list[tuple[str, str]], bool]:
    entries: list[tuple[str, str]] = []
    truncated = False
    visited = 0

    def walk(directory: Path, rel: str, depth: int) -> list[tuple[str, str]]:
        nonlocal visited
        visited += 1
        if visited > 4000:
            return [(Path(rel).name, rel)]
        if _has_license(directory) or depth >= MAX_VENDOR_DEPTH:
            return [(Path(rel).name, rel)]
        try:
            children = [
                child
                for child in sorted(directory.iterdir())
                if child.is_dir() and not child.name.startswith(".") and child.name != "__pycache__"
            ]
        except OSError:
            return [(Path(rel).name, rel)]
        if not children or len(children) > MAX_VENDOR_CHILDREN:
            return [(Path(rel).name, rel)]
        found: list[tuple[str, str]] = []
        for child in children:
            found.extend(walk(child, f"{rel}/{child.name}", depth + 1))
        return found or [(Path(rel).name, rel)]

    for rel in vendor_dirs(root):
        for name, path in walk(root / rel, rel, 0):
            if len(entries) >= MAX_VENDOR_ENTRIES:
                truncated = True
                break
            entries.append((name, path))
        if truncated:
            break

    used: set[str] = set()
    unique: list[tuple[str, str]] = []
    for name, path in entries:
        candidate = name
        if candidate in used:
            candidate = path.replace("/", "-")
        if candidate in used:
            candidate = f"{candidate}-{len(unique)}"
        used.add(candidate)
        unique.append((candidate, path))
    return unique, truncated


def load_declared(root: Path) -> tuple[set[tuple[str, str]], set[str]]:
    refs: set[tuple[str, str]] = set()
    vendored: set[str] = set()
    for name in FOSSA_DEPS_NAMES:
        path = root / name
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if MARKER in text:
            continue
        try:
            if path.suffix.lower() == ".json":
                data = json.loads(text)
            else:
                data = yaml_lite.load(text)
        except (json.JSONDecodeError, ValueError):
            continue
        if not isinstance(data, dict):
            continue
        for item in data.get("referenced-dependencies") or []:
            if isinstance(item, dict) and item.get("type") and item.get("name"):
                refs.add((str(item["type"]).lower(), str(item["name"]).lower()))
        for item in data.get("vendored-dependencies") or []:
            if isinstance(item, dict) and item.get("path"):
                vendored.add(str(item["path"]).strip().strip("/"))
    return refs, vendored


def plan(
    root: Path,
    config: Config,
    *,
    mode: str = "missing",
    limit: int = DEFAULT_LIMIT,
    declared: tuple[set[tuple[str, str]], set[str]] | None = None,
) -> DepsPlan:
    if mode not in ("missing", "all"):
        raise ValueError(f"unknown mode: {mode}")
    result = deps.collect(root, config)
    out = DepsPlan(mode=mode, total_packages=len(result.packages))
    declared_refs, declared_vendored = declared or (set(), set())
    seen: set[tuple[str, str, str]] = set()

    for package in result.packages:
        dep_type = ECOSYSTEM_TYPES.get(package.ecosystem)
        if not dep_type:
            out.skip(f"FOSSA 不支持的生态（{package.ecosystem}）")
            continue
        if package.locator.startswith(("url:", "file:")):
            out.skip("本地 / Git 路径依赖（无版本可声明）")
            continue
        name = package.name.strip()
        if not name:
            continue
        if (dep_type, name.lower()) in declared_refs:
            out.skip("已有手写声明（跳过）")
            continue
        key = (dep_type, name, package.version)
        if key in seen:
            continue
        seen.add(key)
        if mode == "all":
            out.referenced.append((dep_type, name, package.version))
            if not package.version:
                out.unpinned += 1
        else:
            out.skip("FOSSA 自己能扫到（missing 模式不重复声明）")

    if mode == "all":
        out.referenced.sort(key=lambda item: (item[0], item[1].lower(), item[2]))
        if len(out.referenced) > limit:
            out.referenced = out.referenced[:limit]
            out.truncated = True

    used_names: set[str] = set()
    vendored, vendored_truncated = vendored_entries(root)
    plan_result_vendored: list[tuple[str, str]] = []
    for name, rel in vendored:
        cleaned = rel.strip().strip("/")
        if not cleaned or cleaned in declared_vendored:
            out.skip("vendored 目录已声明")
            continue
        candidate = name
        if candidate in used_names:
            candidate = cleaned.replace("/", "-")
        used_names.add(candidate)
        plan_result_vendored.append((candidate, cleaned))
    out.vendored = plan_result_vendored
    out.vendored_truncated = vendored_truncated
    return out


def _quote(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render(plan_result: DepsPlan) -> str:
    stamp = dt.datetime.now().astimezone().isoformat(timespec="seconds")
    lines = [
        f"{MARKER} {__version__} — 重新生成会覆盖本文件，手写内容请放到别的文件",
        f"# 生成时间：{stamp}",
        "# 用途：声明 FOSSA 自己扫不到的依赖（vendored 代码、FOSSA 不支持的生态）",
        "# 读取：fossa analyze 会自动读取仓库根目录的 fossa-deps.yml",
    ]
    if plan_result.mode == "all":
        lines.extend(
            [
                "# " + "=" * 64,
                "# !!! 警告：all 模式是全量声明，会与 FOSSA 自动扫描重叠 !!!",
                "# FOSSA 本来就能扫到下面这些包；重复声明可能让报告里出现",
                "# 「来源不同」的重复条目，而且每次升级依赖都必须重新生成这个文件。",
                "# 只在以下情况使用 all：",
                "#   1) FOSSA 的构建策略失败（例如复杂 Maven / Gradle 工程只拿到直接依赖）",
                "#   2) 清单格式 FOSSA 不支持、但能映射到它已知的 type",
                "# 平时请用缺省模式：provemark fossa-deps   （只补盲区）",
                "# " + "=" * 64,
                f"# 模式：all — 导出 FOSSA 支持的全部依赖（{len(plan_result.referenced)} 条）",
            ]
        )
    else:
        lines.append("# 模式：missing — 只补 FOSSA 扫不到的部分（vendored 目录）")
    if plan_result.unpinned:
        lines.append(f"# 注意：{plan_result.unpinned} 条没有固定版本，FOSSA 会取注册表最新版")
    if plan_result.truncated:
        lines.append("# 注意：条目超过上限，已截断；需要完整列表请调大 --limit")
    if plan_result.vendored_truncated:
        lines.append("# 注意：vendored 目录超过上限，已截断；剩余目录请手工补充")
    if plan_result.referenced:
        lines.append("referenced-dependencies:")
        for dep_type, name, version in plan_result.referenced:
            lines.append(f"  - type: {dep_type}")
            lines.append(f"    name: {_quote(name)}")
            if version:
                lines.append(f"    version: {_quote(version)}")
    if plan_result.vendored:
        lines.append("vendored-dependencies:")
        for name, path in plan_result.vendored:
            lines.append(f"  - name: {_quote(name)}")
            lines.append(f"    path: {_quote(path)}")
    return "\n".join(lines) + "\n"


def write(plan_result: DepsPlan, target: Path, *, force: bool = False) -> tuple[Path, bool]:
    target = target.expanduser()
    redirected = False
    if target.exists():
        try:
            existing = target.read_text(encoding="utf-8", errors="replace")
        except OSError:
            existing = ""
        if MARKER not in existing and not force:
            target = target.with_name(f"{target.stem}.provemark{target.suffix}")
            redirected = True
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(plan_result), encoding="utf-8")
    return target, redirected
